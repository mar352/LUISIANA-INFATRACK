/**
 * ocrGeotag.ts
 *
 * Optical Character Recognition (OCR) Engine for Site Photo Documentation
 * INFA-TRACK · Office of the Municipal Planning and Development Coordinator (MPDC)
 * Municipality of Luisiana, Laguna
 *
 * Recognizes GPS coordinates, watermarks, timestamps, elevation, and barangay names
 * stamped onto site photos taken with GPS Map Camera, SpotLens, NoteCam, Solocator,
 * Timestamp Camera, OpenCamera, or any mobile camera application.
 */

import Tesseract from "tesseract.js";

export interface GeotagCoordinates {
  lat: number;
  lon: number;
}

export interface OcrGeotagResult {
  hasCoordinates: boolean;
  coords?: GeotagCoordinates;
  altitude?: number;
  dateTime?: string;
  detectedBarangay?: string;
  rawText: string;
  extractionMethod?:
    | "phil-flexible"
    | "decimal-pair"
    | "labeled"
    | "dms"
    | "ddm"
    | "directional-phil"
    | "directional-general";
}

