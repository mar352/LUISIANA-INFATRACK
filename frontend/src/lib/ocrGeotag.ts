/**
 * Intelligent parser that extracts geographic coordinates and metadata
 * from raw OCR text generated by Tesseract.
 */
export function parseCoordinatesFromOcrText(rawText: string): OcrGeotagResult {
  if (!rawText || typeof rawText !== "string") {
    return { hasCoordinates: false, rawText: "" };
  }

  const clean = rawText.replace(/\r\n/g, "\n");

  // 1. Detect any Luisiana Barangay mentioned in the text
  let detectedBarangay: string | undefined;
  for (const brgy of LUISIANA_BARANGAYS) {
    const brgyShort = brgy.replace(" (Poblacion)", "");
    const regex = new RegExp(`\\b${escapeRegExp(brgyShort)}\\b`, "i");
    if (regex.test(clean)) {
      detectedBarangay = brgy;
      break;
    }
  }

  // Also check Roman / Arabic numeral variations for Poblacion Zones (e.g. "Zone 1" -> "Barangay Zone I (Poblacion)")
  if (!detectedBarangay) {
    const zoneMatch = clean.match(/Zone\s*([1-8]|I{1,3}|IV|V|VI{1,3}|VIII)\b/i);
    if (zoneMatch) {
      const z = zoneMatch[1].toUpperCase();
      const zoneMap: Record<string, string> = {
        "1": "Barangay Zone I (Poblacion)",
        "I": "Barangay Zone I (Poblacion)",
        "2": "Barangay Zone II (Poblacion)",
        "II": "Barangay Zone II (Poblacion)",
        "3": "Barangay Zone III (Poblacion)",
        "III": "Barangay Zone III (Poblacion)",
        "4": "Barangay Zone IV (Poblacion)",
        "IV": "Barangay Zone IV (Poblacion)",
        "5": "Barangay Zone V (Poblacion)",
        "V": "Barangay Zone V (Poblacion)",
        "6": "Barangay Zone VI (Poblacion)",
        "VI": "Barangay Zone VI (Poblacion)",
        "7": "Barangay Zone VII (Poblacion)",
        "VII": "Barangay Zone VII (Poblacion)",
        "8": "Barangay Zone VIII (Poblacion)",
        "VIII": "Barangay Zone VIII (Poblacion)",
      };
      if (zoneMap[z]) detectedBarangay = zoneMap[z];
    }
  }

  // 2. Extract altitude / elevation if present (e.g. "Alt: 120.5m", "Elevation: 120m")
  let altitude: number | undefined;
  const altMatch = clean.match(/(?:alt(?:itude)?|elev(?:ation)?|altitude)[:\s=]+([0-9]+(?:\.[0-9]+)?)\s*(?:m|meters)?/i);
  if (altMatch) {
    altitude = Number(parseFloat(altMatch[1]).toFixed(1));
  }

  // 3. Extract date/time stamp if present
  let dateTime: string | undefined;
  // Check for month name dates like "Oct 26, 2023 11:31 AM" or "F0ct 26,2023 11:31 AM"
  const monthDateMatch = clean.match(/(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|[0O]ct|Nov|Dec)[a-z]*\.?\s*\d{1,2},?\s*\d{4}(?:\s+\d{1,2}:\d{2}(?::\d{2})?(?:\s*[APap][Mm])?)?/i);
  if (monthDateMatch) {
    dateTime = monthDateMatch[0].replace(/^0ct/i, "Oct").trim();
  } else {
    // Check for numeric dates like "2026-10-23" or "10/23/2026"
    const numDateMatch = clean.match(/(\d{4}[-/.]\d{1,2}[-/.]\d{1,2}|\d{1,2}[-/.]\d{1,2}[-/.]\d{4})(?:\s+(\d{1,2}:\d{2}(?::\d{2})?(?:\s*[APap][Mm])?))?/);
    if (numDateMatch) {
      dateTime = numDateMatch[0].trim();
    }
  }

  // 4. COORDINATE PARSING STRATEGIES

  // Strategy A: Philippine-tuned Flexible Regex
  // Specifically optimized for Laguna/Philippines coordinates (Lat ~14.xxx, Lon ~121.xxx)
  // Handles faint/missing decimal dots (e.g. "S142154°N"), comma decimals ("14,2154"),
  // and misread East characters (such as "°F", "°B", "°C" instead of "°E" due to grass/textures).
  const philLatRegex = /(?:^|[^\d.])(?:[A-Za-z]*)?(14)(?:[.,](\d{3,7})|(\d{4,6}))\s*°?\s*([NSns])?/i;
  const philLonRegex = /(?:^|[^\d.])(?:[A-Za-z]*)?(121)(?:[.,](\d{3,7})|(\d{4,6}))\s*°?\s*([EFefWwBbCc])?/i;

  const latM = clean.match(philLatRegex);
  const lonM = clean.match(philLonRegex);

  if (latM && lonM) {
    const latDec = latM[2] || latM[3];
    const lonDec = lonM[2] || lonM[3];
    let lat = parseFloat(`14.${latDec}`);
    let lon = parseFloat(`121.${lonDec}`);
    if (latM[4] && latM[4].toUpperCase() === "S") lat = -lat;
    if (lonM[4] && lonM[4].toUpperCase() === "W") lon = -lon;

    if (isValidPhilippineCoordinate(lat, lon)) {
      return {
        hasCoordinates: true,
        coords: { lat: Number(lat.toFixed(6)), lon: Number(lon.toFixed(6)) },
        altitude,
        dateTime,
        detectedBarangay,
        rawText: clean,
        extractionMethod: "phil-flexible",
      };
    }
  }

  // Strategy B: Standard Decimal Pair with dot or comma (any valid Philippine lat 4-22, lon 116-128)
  const decimalPairRegex = /([0-9]{1,2})[.,]([0-9]{3,8})\s*°?\s*([NSns])?[\s,;|\/\\]+([0-9]{2,3})[.,]([0-9]{3,8})\s*°?\s*([EFefWw]?)/gi;
  let pMatch;
  while ((pMatch = decimalPairRegex.exec(clean)) !== null) {
    let lat = parseFloat(`${pMatch[1]}.${pMatch[2]}`);
    let lon = parseFloat(`${pMatch[4]}.${pMatch[5]}`);
    if (pMatch[3] && pMatch[3].toUpperCase() === "S") lat = -lat;
    if (pMatch[6] && pMatch[6].toUpperCase() === "W") lon = -lon;
    if (isValidPhilippineCoordinate(lat, lon)) {
      return {
        hasCoordinates: true,
        coords: { lat: Number(lat.toFixed(6)), lon: Number(lon.toFixed(6)) },
        altitude,
        dateTime,
        detectedBarangay,
        rawText: clean,
        extractionMethod: "decimal-pair",
      };
    }
  }

  // Strategy C: Labeled Lat & Lon (e.g. "Lat: 14.183700 N", "Latitude 14.1837", "Lon: 121.508900 E")
  const latLabeledRegex = /(?:lat(?:itude)?[:\s=]+)([0-9]{1,2}(?:[.,][0-9]+)?)\s*°?\s*([NSns])?/i;
  const lonLabeledRegex = /(?:lon(?:g(?:itude)?)?[:\s=]+)([0-9]{2,3}(?:[.,][0-9]+)?)\s*°?\s*([EFefWw])?/i;

  const latMatch = clean.match(latLabeledRegex);
  const lonMatch = clean.match(lonLabeledRegex);

  if (latMatch && lonMatch) {
    let lat = parseFloat(latMatch[1].replace(",", "."));
    let lon = parseFloat(lonMatch[1].replace(",", "."));
    if (latMatch[2] && latMatch[2].toUpperCase() === "S") lat = -lat;
    if (lonMatch[2] && lonMatch[2].toUpperCase() === "W") lon = -lon;

    if (isValidPhilippineCoordinate(lat, lon)) {
      return {
        hasCoordinates: true,
        coords: { lat: Number(lat.toFixed(6)), lon: Number(lon.toFixed(6)) },
        altitude,
        dateTime,
        detectedBarangay,
        rawText: clean,
        extractionMethod: "labeled",
      };
    }
  }

  // Strategy D: Degree-Minute-Second (DMS) (e.g. "14°11'01.3\"N 121°30'32.0\"E")
  const dmsLatRegex = /([0-9]{1,2})\s*[°*o]\s*([0-9]{1,2})\s*['′’]\s*([0-9]{1,2}(?:[.,][0-9]+)?)\s*["″”]?\s*([NSns])/i;
  const dmsLonRegex = /([0-9]{2,3})\s*[°*o]\s*([0-9]{1,2})\s*['′’]\s*([0-9]{1,2}(?:[.,][0-9]+)?)\s*["″”]?\s*([EFefWw])/i;

  const dmsLatMatch = clean.match(dmsLatRegex);
  const dmsLonMatch = clean.match(dmsLonRegex);

  if (dmsLatMatch && dmsLonMatch) {
    const latDeg = parseFloat(dmsLatMatch[1]);
    const latMin = parseFloat(dmsLatMatch[2]);
    const latSec = parseFloat(dmsLatMatch[3].replace(",", "."));
    let lat = latDeg + latMin / 60 + latSec / 3600;
    if (dmsLatMatch[4].toUpperCase() === "S") lat = -lat;

    const lonDeg = parseFloat(dmsLonMatch[1]);
    const lonMin = parseFloat(dmsLonMatch[2]);
    const lonSec = parseFloat(dmsLonMatch[3].replace(",", "."));
    let lon = lonDeg + lonMin / 60 + lonSec / 3600;
    if (dmsLonMatch[4].toUpperCase() === "W") lon = -lon;

    if (isValidPhilippineCoordinate(lat, lon)) {
      return {
        hasCoordinates: true,
        coords: { lat: Number(lat.toFixed(6)), lon: Number(lon.toFixed(6)) },
        altitude,
        dateTime,
        detectedBarangay,
        rawText: clean,
        extractionMethod: "dms",
      };
    }
  }

  return {
    hasCoordinates: false,
    altitude,
    dateTime,
    detectedBarangay,
    rawText: clean,
  };
}

function isValidPhilippineCoordinate(lat: number, lon: number): boolean {
  return Number.isFinite(lat) && Number.isFinite(lon) && lat >= 4 && lat <= 22 && lon >= 116 && lon <= 128;
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Executes Optical Character Recognition (OCR) on an image file.
 * Fast dual-pass architecture:
 * 1. Direct pass on file (processes original uncompressed image via Tesseract worker)
 * 2. Preprocessed high-contrast canvas pass (boosts text readability if direct pass has no coordinates)
 */
export async function recognizePhotoWatermarkOcr(
  file: File,
  onProgress?: (progress: number) => void
): Promise<OcrGeotagResult> {
  // Pass 1: Direct File Recognition
  try {
    const res = await Tesseract.recognize(file, "eng", {
      logger: (m) => {
        if (m.status === "recognizing text" && typeof m.progress === "number" && onProgress) {
          onProgress(m.progress);
        }
      },
    });

    if (res?.data?.text) {
      const parsed = parseCoordinatesFromOcrText(res.data.text);
      if (parsed.hasCoordinates) {
        return parsed;
      }
    }
  } catch (directErr) {
    console.warn("[OCR Direct Pass Notice]:", directErr);
  }

  // Pass 2: High-Contrast Watermark Banner Fallback
  try {
    const canvas = await createHighContrastWatermarkCanvas(file);
    if (canvas) {
      const res = await Tesseract.recognize(canvas, "eng");
      if (res?.data?.text) {
        const parsed = parseCoordinatesFromOcrText(res.data.text);
        if (parsed.hasCoordinates) {
          return parsed;
        }
      }
    }
  } catch (canvasErr) {
    console.warn("[OCR Canvas Pass Notice]:", canvasErr);
  }

  return {
    hasCoordinates: false,
    rawText: "",
  };
}

async function createHighContrastWatermarkCanvas(file: File): Promise<HTMLCanvasElement | null> {
  if (typeof document === "undefined") return null;
  const objectUrl = URL.createObjectURL(file);
  try {
    const img = await loadImage(objectUrl);
    const canvas = document.createElement("canvas");
    const bannerHeight = Math.max(160, Math.floor(img.height * 0.45));
    const bannerStartY = Math.max(0, img.height - bannerHeight);

    const targetWidth = Math.min(1800, img.width);
    const scale = targetWidth / img.width;
    const targetHeight = Math.floor(bannerHeight * scale);

    canvas.width = targetWidth;
    canvas.height = targetHeight;

    const ctx = canvas.getContext("2d");
    if (!ctx) return null;

    ctx.drawImage(img, 0, bannerStartY, img.width, bannerHeight, 0, 0, targetWidth, targetHeight);

    const imgData = ctx.getImageData(0, 0, targetWidth, targetHeight);
    const d = imgData.data;
    for (let i = 0; i < d.length; i += 4) {
      const gray = 0.299 * d[i] + 0.587 * d[i + 1] + 0.114 * d[i + 2];
      const boosted = gray > 140 ? 255 : Math.max(0, gray * 0.5);
      d[i] = boosted;
      d[i + 1] = boosted;
      d[i + 2] = boosted;
    }
    ctx.putImageData(imgData, 0, 0);
    return canvas;
  } finally {
    URL.revokeObjectURL(objectUrl);
  }
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = (err) => reject(err);
    img.src = src;
  });
}
